#!/usr/bin/env python3
"""make_predictions_table.py — generate PREDICTIONS.md from the register.

The status table is generated, never hand-edited, so it cannot drift from the
register. `--check` exits 1 if PREDICTIONS.md differs from what would be
generated (used by verification/claims.json and CI).

Usage:
    python3 pipelines/make_predictions_table.py          # write PREDICTIONS.md
    python3 pipelines/make_predictions_table.py --check  # verify it is current
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
REGISTER = REPO_ROOT / "predictions"
OUT = REPO_ROOT / "PREDICTIONS.md"
NUMBER_WORDS = {9: "nine", 10: "ten", 11: "eleven", 12: "twelve", 13: "thirteen", 14: "fourteen",
                15: "fifteen", 16: "sixteen", 17: "seventeen", 18: "eighteen", 19: "nineteen", 20: "twenty"}


def frontmatter(text: str) -> dict:
    m = re.match(r"^---\n(.*?)\n---\n", text, re.S)
    out = {}
    for line in (m.group(1) if m else "").splitlines():
        if ":" in line:
            k, v = line.split(":", 1)
            out[k.strip()] = v.strip()
    return out


def verdict(entry: Path) -> str:
    card = entry / "scorecard.md"
    if not card.is_file():
        return "awaiting data"
    m = re.search(r"\*\*Outcome:\*\*\s*(\S+)\s+([A-Z-]+)", card.read_text(encoding="utf-8"))
    return f"{m.group(1)} {m.group(2)}" if m else "scored"


def build() -> str:
    rows, counts = [], {}
    for entry in sorted(p for p in REGISTER.iterdir() if p.is_dir()):
        fm = frontmatter((entry / "prediction.md").read_text(encoding="utf-8"))
        v = verdict(entry)
        key = v.split()[-1] if v != "awaiting data" else "awaiting data"
        counts[key] = counts.get(key, 0) + 1
        tier = fm.get("tier", "").split(" (")[0]
        target = fm.get("target_dataset", "").split(";")[0].split(" (")[0]
        when = fm.get("target_release_date", "").split(" (")[0].split(";")[0]
        title = fm.get("title", "").replace("|", "/")
        rows.append(f"| [{fm.get('prediction_id', entry.name)}](predictions/{entry.name}/) | {title} | {tier} | {v} | {target} | {when} |")
    n = len(rows)
    n_scored = sum(1 for p in REGISTER.iterdir() if (p / "scorecard.md").is_file())
    summary = ", ".join(f"{counts[k]} {k}" for k in ("PASS", "FAIL", "SUB-THRESHOLD", "awaiting data") if k in counts)
    return "\n".join([
        "# Registered predictions",
        "",
        "<!-- GENERATED by pipelines/make_predictions_table.py from the register. Do not edit by hand. -->",
        "",
        f"The register holds {NUMBER_WORDS.get(n, str(n))} registered predictions ({summary}). "
        f"{n_scored} active scorers compare scored entries with published data at the registered |z| < 3 rule. "
        "Most PASS verdicts are retrodictive consistency checks or exact nulls shared with ΛCDM; see "
        "[METHOD.md](METHOD.md) for what each kind of verdict does and does not show, and "
        "[OPEN_PROBLEMS.md](OPEN_PROBLEMS.md) for flagged issues. Titles, targets and dates are the registered "
        "wording; later corrections (for example, P1's forward target is now the full five-year DESI release) are "
        "recorded inside each entry.",
        "",
        "| ID | Prediction | Tier | Verdict | Target data | When |",
        "|---|---|---|---|---|---|",
        *rows,
        "",
    ])


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="exit 1 if PREDICTIONS.md is not current")
    args = ap.parse_args(argv)
    text = build()
    if args.check:
        current = OUT.read_text(encoding="utf-8") if OUT.is_file() else ""
        if current != text:
            print("PREDICTIONS.md is out of date: run python3 pipelines/make_predictions_table.py")
            return 1
        print("PREDICTIONS.md is current")
        return 0
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(REPO_ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
