#!/usr/bin/env python3
"""Infer the mass variation required by SPARC rotation curves. Diagnostic only."""

import argparse
import json
import math
import statistics
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import joint_fit as jf  # noqa: E402

DATA = HERE.parent / "data" / "sparc"
OUT_JSON = HERE / "sparc_mass_budget.json"
OUT_MD = HERE / "sparc_mass_budget.md"
Q_MAX, INC_MIN = 2, 30
DISK, BULGE, DISK_DEX = 0.5, 0.7, 0.1


def catalogue():
    text = (DATA / "SPARC_Lelli2016c.mrt").read_text(encoding="ascii")
    # The distributed rows have a blank between successive fields, in addition
    # to the field widths in the byte-layout header.
    rows = text.rsplit("-" * 80 + "\n", 1)[1].splitlines()
    return [{"galaxy": row[:11].strip(), "inc_deg": float(row[31:35]),
             "v_flat_km_s": float(row[101:106]), "quality": int(row[113:116])} for row in rows]


def load_curve(name):
    lines = (DATA / "rotmod" / (name + "_rotmod.dat")).read_text(encoding="ascii").splitlines()
    return [tuple(map(float, line.split()[:6])) for line in lines if line.strip() and not line.startswith("#")]


def measure(points, v_flat):
    """Integrate signed radial forces and propagate each independent speed error once."""
    radii = [p[0] for p in points]
    if len(radii) < 2 or radii[0] <= 0 or any(r >= s for r, s in zip(radii, radii[1:])):
        raise ValueError("integration needs positive, strictly increasing radii")
    half_steps = [0.5 * math.log(s / r) for r, s in zip(radii, radii[1:])]
    weights = [a + b for a, b in zip([0.0] + half_steps, half_steps + [0.0])]
    observed = baryon = disk = variance = 0.0
    for w, (_, v, error, vg, vd, vb) in zip(weights, points):
        bar2 = vg * abs(vg) + DISK * vd * abs(vd) + BULGE * vb * abs(vb)
        observed += w * v**2
        baryon += w * bar2
        disk += w * DISK * vd * abs(vd)
        variance += (w * 2 * v * error)**2

    delta = (observed - baryon) / jf.C**2
    return {"n_points": len(points), "r_in_kpc": radii[0], "r_out_kpc": radii[-1],
            "delta_ln_A": delta, "sigma_delta_ln_A_errV": math.sqrt(variance) / jf.C**2,
            "delta_ln_A_at_low_disk_ML": delta - disk / jf.C**2 * (10**-DISK_DEX - 1),
            "delta_ln_A_at_high_disk_ML": delta - disk / jf.C**2 * (10**DISK_DEX - 1),
            "delta_phi_bar_over_c2": baryon / jf.C**2,
            "delta_ln_A_over_baryon_potential": (observed - baryon) / baryon if baryon else None,
            "delta_ln_A_over_vflat2_c2": (observed - baryon) / v_flat**2 if v_flat > 0 else None,
            "outer_g_lens_over_g_obs": bar2 / points[-1][1]**2}


def distribution(values):
    cuts = statistics.quantiles(values, n=100, method="inclusive")
    return {"count": len(values), "p16": cuts[15], "median": statistics.median(values),
            "p84": cuts[83], "max": max(values)}


def log_fit(rows):
    pairs = [(math.log(r["v_flat_km_s"]), math.log(r["delta_ln_A"])) for r in rows
             if r["v_flat_km_s"] > 0 and r["delta_ln_A"] > 0]
    xs, ys = zip(*pairs)
    xbar, ybar = statistics.mean(xs), statistics.mean(ys)
    xx = sum((x - xbar)**2 for x in xs)
    yy = sum((y - ybar)**2 for y in ys)
    xy = sum((x - xbar) * (y - ybar) for x, y in pairs)
    return {"count": len(pairs), "slope": xy / xx, "pearson_r": xy / math.sqrt(xx * yy)}


def analyse():
    sample = []
    galaxies = catalogue()
    for galaxy in galaxies:
        if galaxy["quality"] <= Q_MAX and galaxy["inc_deg"] >= INC_MIN:
            sample.append({**galaxy, **measure(load_curve(galaxy["galaxy"]), galaxy["v_flat_km_s"])})
    keys = ("delta_ln_A", "delta_ln_A_over_vflat2_c2", "delta_ln_A_over_baryon_potential", "outer_g_lens_over_g_obs")
    stats = {key: distribution([r[key] for r in sample if r[key] is not None]) for key in keys}
    return {"catalogue_count": len(galaxies), "sample_count": len(sample),
            "inputs": {"quality_max": Q_MAX, "inclination_min_deg": INC_MIN, "disk_ML": DISK, "bulge_ML": BULGE,
                       "disk_sensitivity_dex": DISK_DEX, "c_km_s": jf.C},
            "nonpositive_excursions": sum(r["delta_ln_A"] <= 0 for r in sample),
            "distributions": stats, "log_fit": log_fit(sample),
            "min_v2_over_2M2_for_largest_excursion": math.expm1(stats["delta_ln_A"]["max"]),
            "galaxies": sample}


