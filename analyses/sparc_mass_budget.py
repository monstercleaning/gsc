def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    result = jf._round(analyse())
    if args.check:
        saved = json.loads(OUT_JSON.read_text(encoding="utf-8"))
        problems = jf._compare(result, saved)
        if render_markdown(saved) != OUT_MD.read_text(encoding="utf-8"):
            problems.append("Markdown differs from the rendering of the saved JSON")
        for problem in problems[:10]:
            print("DIFFERS", problem)
        print("SPARC check failed" if problems else "SPARC mass budget reproduces its saved output")
        return int(bool(problems))
    OUT_JSON.write_text(json.dumps(result, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    OUT_MD.write_text(render_markdown(result), encoding="utf-8")
    print(f"wrote {OUT_JSON.name} and {OUT_MD.name}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
